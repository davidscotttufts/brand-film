// Makes a web page the film's source: its text for the facts check, and a list
// of the pictures and videos on it, for the shot list and for footage.
//
//   npm run source -- https://example.com/launch      # writes source.txt, source.media.json, source.lock.json
//   npm run source -- page.html                       # a saved page works too
//   npm run source                                    # re-fetch film.json sourceUrl; says if the text changed
//
// source.txt is the page's readable text (scripts, styles, navigation and
// footers removed), with the URL and the date it was read at the top. film.json
// `source` points at it (set when empty), so `npm run render` fails if a fact
// on screen is no longer on the page. source.media.json lists every image,
// video and embedded player with its absolute URL and alt text, each with
// "licence": null: nothing from it goes into the film until clips.json gives
// it a licence (references/footage.md). source.lock.json records the URL, when
// it was read and a hash of the text, so a re-fetch shows whether the page
// changed under the film.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { htmlToText, pageMedia, pageTitle } from './lib/page.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const filmPath = join(here, 'film.json');
const film = JSON.parse(readFileSync(filmPath, 'utf8'));
const lockPath = join(here, 'source.lock.json');
const prev = existsSync(lockPath) ? JSON.parse(readFileSync(lockPath, 'utf8')) : null;
const arg = process.argv[2] ?? film.sourceUrl;
if (!arg) { console.error('usage: npm run source -- <url | page.html>'); process.exit(1); }

let html, base;
if (/^https?:\/\//.test(arg)) {
  const r = await fetch(arg, { headers: { 'user-agent': 'brand-film-source (+https://github.com/davidscotttufts/brand-film)', accept: 'text/html,*/*' }, signal: AbortSignal.timeout(30000) }).catch((e) => {
    console.error(`[source] could not reach ${arg}: ${e.cause?.code ?? e.message}. Allow the site in the sandbox or proxy, or save the page and pass the file.`);
    process.exit(1);
  });
  if (!r.ok) { console.error(`[source] ${arg} answered ${r.status}`); process.exit(1); }
  html = await r.text();
  base = r.url || arg;
} else {
  const file = resolve(process.cwd(), arg);
  if (!existsSync(file)) { console.error(`[source] no such file: ${arg}`); process.exit(1); }
  html = readFileSync(file, 'utf8');
  base = `file://${file}`;
}

const title = pageTitle(html);
const text = htmlToText(html);
const media = pageMedia(html, base);
const hash = createHash('sha256').update(text).digest('hex').slice(0, 16);
const fetchedAt = new Date().toISOString();
writeFileSync(join(here, 'source.txt'), `Source: ${base}\nRead: ${fetchedAt.slice(0, 10)}\nTitle: ${title}\n\n${text}\n`);
writeFileSync(join(here, 'source.media.json'), JSON.stringify({ $comment: 'Pictures and videos on the source page. None is used until clips.json names it with a licence (references/footage.md).', page: base, media: media.map((m) => ({ ...m, licence: null })) }, null, 2) + '\n');
writeFileSync(lockPath, JSON.stringify({ $comment: 'The source page as the film read it. Committed; generated by npm run source.', url: base, title, fetchedAt, textHash: hash, words: text.split(/\s+/).length, media: media.length }, null, 2) + '\n');
if (!film.source) film.source = 'source.txt';
if (/^https?:/.test(base)) film.sourceUrl = base;
writeFileSync(filmPath, JSON.stringify(film, null, 2) + '\n');

console.log(`[source] "${title}": ${text.split(/\s+/).length} words -> source.txt; ${media.length} picture(s) and video(s) -> source.media.json`);
if (prev && prev.textHash !== hash) console.warn(`[source] the page's text has CHANGED since ${prev.fetchedAt.slice(0, 10)}; re-check the facts (npm run render checks film.json facts against it)`);
if (film.source !== 'source.txt') console.log(`[source] film.json source is ${film.source}; point it at source.txt to check the facts against this page`);
