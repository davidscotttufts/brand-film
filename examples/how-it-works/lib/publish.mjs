// What a player or a channel needs beside the film: titles, a description,
// chapters, credits and the files. Written by npm run render to
// out/<basename>.publish.json (and .chapters.txt), from film.json `publish`
// (titles and a description Claude writes with the script) and the takes'
// `chapter` names.
//
// YouTube's chapter rules: the first starts at 0:00, at least three, each ten
// seconds or longer. Chapters that break them are still written, with a
// warning, since other players (and a page's own chapter list) don't need them.

const clock = (s) => { const t = Math.floor(s); return `${Math.floor(t / 60)}:${String(t % 60).padStart(2, '0')}`; };

/** Chapters from takes that name one: [{ at, title }], the first moved to 0:00. Returns { chapters, warnings }. */
export function chapters(takes, duration) {
  const list = takes.filter((t) => t.chapter).map((t) => ({ at: t.at, title: t.chapter }));
  const warnings = [];
  if (!list.length) return { chapters: [], warnings };
  list[0].at = 0;
  if (list.length < 3) warnings.push(`${list.length} chapter(s); YouTube shows chapters only when there are three or more`);
  list.forEach((c, i) => {
    const end = list[i + 1]?.at ?? duration;
    if (end - c.at < 10) warnings.push(`chapter "${c.title}" is ${(end - c.at).toFixed(1)}s; YouTube needs 10s or more`);
  });
  return { chapters: list.map((c) => ({ ...c, time: clock(c.at) })), warnings };
}

export const chaptersText = (list) => list.map((c) => `${c.time} ${c.title}`).join('\n');

/**
 * The publish record. film: film.json; takes: narration.json takes; credits:
 * [{ id, credit, licence, source }] from media.lock.json; files: what render wrote.
 */
export function publishInfo({ film, takes, duration, credits = [], files = {} }) {
  const p = film.publish ?? {};
  const { chapters: ch, warnings } = chapters(takes, duration);
  const creditLines = credits.filter((c) => c.credit).map((c) => `${c.credit}${c.licence && !/^own$/i.test(c.licence) ? ` (${c.licence})` : ''}`);
  const description = [
    p.description || (takes[0]?.text ?? ''),
    ch.length ? `\n${chaptersText(ch)}` : '',
    creditLines.length ? `\nFootage: ${creditLines.join('; ')}` : '',
  ].filter(Boolean).join('\n').trim();
  if (!p.titles?.length) warnings.push('film.json publish.titles is empty; write three title options with the script');
  return {
    $comment: 'Generated by npm run render from film.json publish, the takes\' chapters and media.lock.json. Paste, don\'t edit: change the sources and re-render.',
    titles: p.titles ?? [],
    description,
    tags: p.tags ?? [],
    chapters: ch,
    credits,
    duration,
    files,
    warnings,
  };
}
