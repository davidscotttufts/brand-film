// Composes the film's score with ElevenLabs music and caches it in music/.
//
//   npm run music                  # then: npm run render
//
// Needs the ElevenLabs CLI, signed in (see lib/elevenlabs.mjs for where the
// key comes from).
//
// The track is keyed by a hash of the model, length and prompt, so re-running
// only recomposes when music.json changes. Set "use": false in music.json for a
// film without a score; the manifest is removed and render.mjs mixes none.
// music/manifest.json records the file render.mjs mixes under the narration.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { account, el } from './lib/elevenlabs.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(readFileSync(join(here, 'music.json'), 'utf8'));
const out = join(here, 'music');
mkdirSync(out, { recursive: true });

if (cfg.use === false) {
  for (const f of readdirSync(out)) rmSync(join(out, f));
  console.log('music.json says use: false; the film renders without a score.');
  process.exit(0);
}

const key = createHash('sha256').update(JSON.stringify([cfg.model, cfg.lengthMs, cfg.prompt])).digest('hex').slice(0, 12);
const file = `score.${key}.mp3`;
if (!existsSync(join(out, file))) {
  const body = { prompt: cfg.prompt, music_length_ms: cfg.lengthMs, model_id: cfg.model, force_instrumental: true };
  el(['music', 'compose', '--json', JSON.stringify(body), '--output', join(out, file)]);
  console.log(`composed ${file}`);
  // The committed record of how the score was made (the audio is not committed).
  writeFileSync(join(here, 'music.lock.json'), JSON.stringify({ $comment: 'How the score was made. Committed; generated by npm run music.', key, model: cfg.model, lengthMs: cfg.lengthMs, prompt: cfg.prompt, generatedAt: new Date().toISOString(), plan: account()?.tier ?? null }, null, 2) + '\n');
} else {
  console.log(`cached   ${file}`);
}
for (const f of readdirSync(out)) if (f !== file && f !== 'manifest.json') rmSync(join(out, f));
writeFileSync(join(out, 'manifest.json'), JSON.stringify({ file: `music/${file}`, lengthMs: cfg.lengthMs, levelDb: cfg.levelDb ?? -10 }, null, 2) + '\n');
